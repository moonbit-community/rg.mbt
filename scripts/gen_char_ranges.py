#!/usr/bin/env python3
"""Generates a MoonBit table of code point ranges computed by the Rust
standard library, so that character predicates match the Rust toolchain
that builds ripgrep (1.97.1). Each table comes from a small Rust program
in scripts/ that prints inclusive hex ranges, one per line:

  scripts/debug_escape.rs  -> core/debug_escape_data.mbt (debug_escape_ranges)
      code points that `{:?}` escapes as \\u{...} inside a string
  scripts/alphanumeric.rs  -> ignore/alphanumeric_data.mbt (alphanumeric_ranges)
      code points for which `char::is_alphanumeric` is true

Usage:
  cargo new chars && cp scripts/<program>.rs chars/src/main.rs
  (cd chars && cargo +1.97.1 run -q --release) > ranges.txt
  python3 scripts/gen_char_ranges.py ranges.txt <name> <program>.rs > <file>.mbt
  moon fmt
"""
import sys
path, name, program = sys.argv[1:4]
pairs = [tuple(int(x, 16) for x in line.split()) for line in open(path) if line.strip()]
print(f'// Generated by scripts/gen_char_ranges.py from scripts/{program}. DO NOT EDIT.')
print('')
print('///|')
print('/// Inclusive code point ranges, as consecutive start/end pairs in')
print('/// ascending order.')
print(f'let {name} : FixedArray[Int] = [')
for a, b in pairs:
    print(f'  0x{a:X}, 0x{b:X},')
print(']')
