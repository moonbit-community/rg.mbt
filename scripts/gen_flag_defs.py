#!/usr/bin/env python3
"""Extracts ripgrep's flag metadata from crates/core/flags/defs.rs into
MoonBit data (core/flag_defs_data.mbt)."""
import re
import sys

sys.path.insert(0, 'scripts')
from rust_tests import parse_rust_string, mbt_str

SRC = sys.argv[1]
OUT = sys.argv[2]
src = open(SRC).read()

order = re.findall(r'^\s*&(\w+),', src[src.index('pub(super) const FLAGS'):src.index('];', src.index('pub(super) const FLAGS'))], re.M)


def block_of(name):
    m = re.search(r'impl Flag for %s \{' % name, src)
    start = m.end()
    depth = 1
    i = start
    while depth:
        c = src[i]
        if c == '"' or src.startswith('r"', i) or src.startswith('r#"', i):
            if c == 'r' and (src[i - 1].isalnum() or src[i - 1] == '_'):
                i += 1
                continue
            _, i = parse_rust_string(src, i)
            continue
        if c == "'" and src[i + 2] == "'":
            i += 3
            continue
        if c == '{':
            depth += 1
        elif c == '}':
            depth -= 1
        i += 1
    return src[start:i - 1]


def method(body, name):
    m = re.search(r'fn %s\(&self\)[^{]*\{' % name, body)
    if not m:
        return None
    rest = body[m.end():]
    return rest


def hyperlink_aliases():
    """Returns alias names sorted by display priority (stable)."""
    asrc = open(SRC.replace('core/flags/defs.rs',
                            'printer/src/hyperlink/aliases.rs')).read()
    asrc = asrc[asrc.index('HYPERLINK_PATTERN_ALIASES'):]
    entries = []
    for m in re.finditer(r'(prioritized_alias|alias)\(\s*(?:(\d+),\s*)?"([^"]+)"', asrc):
        prio = int(m.group(2)) if m.group(2) else 32767
        entries.append((prio, len(entries), m.group(3)))
    entries.sort()
    return [e[2] for e in entries]


def str_method(body, name):
    rest = method(body, name)
    if rest is None:
        return None
    rest = rest.lstrip()
    if rest.startswith('static DOC'):
        # The --hyperlink-format docs are computed from the alias table.
        pieces = []
        i = 0
        while True:
            j = rest.find('doc.push_str(\n', i)
            k = rest.find('r#"', i)
            if k < 0:
                break
            v, i = parse_rust_string(rest, k)
            pieces.append(v)
            if len(pieces) == 2:
                break
        names = hyperlink_aliases()
        mid = ''.join('\\fB%s\\fP%s' % (n, ', ' if idx < len(names) - 1 else '.')
                      for idx, n in enumerate(names))
        return pieces[0] + mid + pieces[1]
    v, _ = parse_rust_string(rest, 0)
    return v


flags = []
for name in order:
    b = block_of(name)
    f = {}
    rest = method(b, 'is_switch')
    f['is_switch'] = rest.strip().startswith('true')
    rest = method(b, 'name_short')
    f['short'] = None
    if rest is not None:
        m = re.match(r"\s*Some\(b'(.)'\)", rest)
        f['short'] = m.group(1) if m else None
    f['long'] = str_method(b, 'name_long')
    rest = method(b, 'aliases')
    f['aliases'] = []
    if rest is not None:
        m = re.match(r'\s*&\[(.*?)\]', rest, re.S)
        f['aliases'] = re.findall(r'"([^"]*)"', m.group(1))
    rest = method(b, 'name_negated')
    f['negated'] = None
    if rest is not None:
        m = re.match(r'\s*Some\("([^"]*)"\)', rest)
        f['negated'] = m.group(1) if m else None
    rest = method(b, 'doc_variable')
    f['var'] = None
    if rest is not None:
        m = re.match(r'\s*Some\("([^"]*)"\)', rest)
        f['var'] = m.group(1) if m else None
    rest = method(b, 'doc_category')
    f['category'] = re.match(r'\s*Category::(\w+)', rest).group(1)
    f['short_doc'] = str_method(b, 'doc_short')
    f['long_doc'] = str_method(b, 'doc_long')
    rest = method(b, 'doc_choices')
    f['choices'] = []
    if rest is not None:
        m = re.match(r'\s*&\[(.*?)\]', rest, re.S)
        if m:
            f['choices'] = re.findall(r'"([^"]*)"', m.group(1))
        elif 'hyperlink_aliases' in rest[:400]:
            f['choices'] = hyperlink_aliases()
        else:
            raise Exception('unknown doc_choices for ' + name)
    rest = method(b, 'completion_type')
    f['completion'] = 'Other'
    if rest is not None:
        f['completion'] = re.match(r'\s*CompletionType::(\w+)', rest).group(1)
    flags.append(f)

with open(OUT, 'w') as out:
    out.write('// Generated by scripts/gen_flag_defs.py from ripgrep\'s\n')
    out.write('// crates/core/flags/defs.rs. DO NOT EDIT.\n\n')
    out.write('///|\n/// All flags, in the same order as ripgrep\'s `FLAGS`.\n')
    out.write('pub let flag_defs : Array[FlagDef] = [\n')
    for f in flags:
        out.write('  {\n')
        out.write('    is_switch: %s,\n' % str(f['is_switch']).lower())
        out.write('    name_short: %s,\n' % ("Some('%s')" % f['short'] if f['short'] else 'None'))
        out.write('    name_long: %s,\n' % mbt_str(f['long']))
        out.write('    aliases: [%s],\n' % ', '.join(mbt_str(a) for a in f['aliases']))
        out.write('    name_negated: %s,\n' % ('Some(%s)' % mbt_str(f['negated']) if f['negated'] else 'None'))
        out.write('    doc_variable: %s,\n' % ('Some(%s)' % mbt_str(f['var']) if f['var'] else 'None'))
        out.write('    doc_category: %s,\n' % f['category'])
        out.write('    doc_short: %s,\n' % mbt_str(f['short_doc']))
        out.write('    doc_long: %s,\n' % mbt_str(f['long_doc']))
        out.write('    doc_choices: [%s],\n' % ', '.join(mbt_str(a) for a in f['choices']))
        out.write('    completion_type: %s,\n' % f['completion'])
        out.write('  },\n')
    out.write(']\n')
print('extracted %d flags' % len(flags))
