#!/usr/bin/env python3
"""Embeds ripgrep's help/man templates and completion scripts as MoonBit
string constants (core/templates_data.mbt)."""
import sys
sys.path.insert(0, 'scripts')
from rust_tests import mbt_str

base = sys.argv[1]
items = [
    ('template_short_help', 'doc/template.short.help'),
    ('template_long_help', 'doc/template.long.help'),
    ('template_rg_man', 'doc/template.rg.1'),
    ('complete_zsh_template', 'complete/rg.zsh'),
    ('complete_fish_prelude', 'complete/prelude.fish'),
    ('complete_encodings_sh', 'complete/encodings.sh'),
]
with open(sys.argv[2], 'w') as out:
    out.write('// Generated by scripts/gen_templates.py from ripgrep\'s\n')
    out.write('// crates/core/flags. DO NOT EDIT.\n')
    for name, path in items:
        text = open(base + '/' + path, encoding='utf-8').read()
        out.write('\n///|\nlet %s : String = %s\n' % (name, mbt_str(text)))
