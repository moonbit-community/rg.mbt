#!/usr/bin/env python3
"""Convert the regex crate's TOML test corpus into MoonBit test data.

Usage: scripts/gen_regex_tests.py <path-to-regex/testdata> <out.mbt>
"""
import glob
import os
import sys
import tomllib

SRC, OUT = sys.argv[1], sys.argv[2]


def unescape(s):
    out = bytearray()
    i = 0
    b = s.encode('utf-8')
    while i < len(b):
        c = b[i]
        if c == 0x5C and i + 1 < len(b):
            n = chr(b[i + 1])
            if n == 'x':
                out.append(int(b[i + 2:i + 4], 16))
                i += 4
                continue
            m = {'n': 10, 'r': 13, 't': 9, '\\': 92, '0': 0, "'": 39,
                 '"': 34}
            if n in m:
                out.append(m[n])
                i += 2
                continue
            out.append(c)
            i += 1
            continue
        out.append(c)
        i += 1
    return bytes(out)


def mbt_bytes(bs):
    out = []
    for x in bs:
        if 0x20 <= x < 0x7F and x not in (0x22, 0x5C, 0x27):
            out.append(chr(x))
        else:
            out.append('\\x%02x' % x)
    return 'b"' + ''.join(out) + '"'


def mbt_str(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch == '\\':
            out.append('\\\\')
        elif ch == '"':
            out.append('\\"')
        elif ch == '\n':
            out.append('\\n')
        elif ch == '\r':
            out.append('\\r')
        elif ch == '\t':
            out.append('\\t')
        elif o < 0x20 or o >= 0x7F:
            out.append('\\u{%x}' % o)
        else:
            out.append(ch)
    return '"' + ''.join(out) + '"'


def main():
    cases = []
    for path in sorted(glob.glob(os.path.join(SRC, '*.toml'))):
        group = os.path.basename(path)[:-5]
        data = tomllib.load(open(path, 'rb'))
        for t in data['test']:
            if isinstance(t['regex'], list):
                continue
            if t.get('match-kind', 'leftmost-first') != 'leftmost-first':
                continue
            if t.get('search-kind', 'leftmost') != 'leftmost':
                continue
            matches = t['matches']
            if matches and isinstance(matches[0], dict):
                continue
            hay = t['haystack']
            if t.get('unescape', False):
                hb = unescape(hay)
            else:
                hb = hay.encode('utf-8')
            groups = []
            for m in matches:
                if isinstance(m[0], list):
                    groups.append([None if not g else (g[0], g[1]) for g in m])
                else:
                    groups.append([(m[0], m[1])])
            lt = t.get('line-terminator')
            if lt is not None:
                lt = unescape(lt)[0]
            cases.append(dict(
                name='%s/%s' % (group, t['name']),
                regex=t['regex'],
                haystack=hb,
                matches=groups,
                compiles=t.get('compiles', True),
                anchored=t.get('anchored', False),
                ci=t.get('case-insensitive', False),
                unicode=t.get('unicode', True),
                utf8=t.get('utf8', True),
                limit=t.get('match-limit'),
                bounds=t.get('bounds'),
                lineterm=lt,
            ))
    with open(OUT, 'w') as f:
        f.write('// Generated by scripts/gen_regex_tests.py. DO NOT EDIT.\n')
        f.write('// Source: the regex crate test corpus (MIT/Apache-2.0).\n\n')
        f.write('///|\npub let cases : Array[TestCase] = [\n')
        for c in cases:
            ms = []
            for g in c['matches']:
                ms.append('[' + ', '.join(
                    'None' if x is None else 'Some((%d, %d))' % x
                    for x in g) + ']')
            b = c['bounds']
            if isinstance(b, dict):
                b = (b['start'], b['end'])
            bounds = 'None' if b is None else 'Some((%d, %d))' % tuple(b)
            limit = 'None' if c['limit'] is None else 'Some(%d)' % c['limit']
            lt = 'None' if c['lineterm'] is None else 'Some(%d)' % c['lineterm']
            f.write('  {\n')
            f.write('    name: %s,\n' % mbt_str(c['name']))
            f.write('    regex: %s,\n' % mbt_str(c['regex']))
            f.write('    haystack: %s,\n' % mbt_bytes(c['haystack']))
            f.write('    matches: [%s],\n' % ', '.join(ms))
            f.write('    compiles: %s,\n' % str(c['compiles']).lower())
            f.write('    anchored: %s,\n' % str(c['anchored']).lower())
            f.write('    case_insensitive: %s,\n' % str(c['ci']).lower())
            f.write('    unicode: %s,\n' % str(c['unicode']).lower())
            f.write('    utf8: %s,\n' % str(c['utf8']).lower())
            f.write('    match_limit: %s,\n' % limit)
            f.write('    bounds: %s,\n' % bounds)
            f.write('    line_terminator: %s,\n' % lt)
            f.write('  },\n')
        f.write(']\n')
    print('wrote %d cases' % len(cases))


main()
