#!/usr/bin/env python3
"""Generate MoonBit Unicode tables from regex-syntax's ucd-generate output.

Usage: scripts/gen_unicode.py <path-to-regex-syntax/src/unicode_tables> <out-dir>

Range tables are encoded as compact strings: each number is written as a
variable-length base-32 sequence where characters in '0'..'O' (0x30..0x4F)
are continuation digits and 'P'..'o' (0x50..0x6F) terminate a number. A range
list is encoded as alternating (start - previous_end, end - start) deltas.
"""
import os
import re
import sys

SRC, OUT = sys.argv[1], sys.argv[2]


def enc_num(n):
    assert n >= 0
    digits = []
    while True:
        digits.append(n & 31)
        n >>= 5
        if n == 0:
            break
    digits.reverse()
    s = ''.join(chr(0x30 + d) for d in digits[:-1])
    return s + chr(0x50 + digits[-1])


def enc_ranges(ranges):
    out = []
    prev = 0
    for (s, e) in ranges:
        out.append(enc_num(s - prev))
        out.append(enc_num(e - s))
        prev = e
    return ''.join(out)


CHAR_RE = r"'((?:\\u\{[0-9A-Fa-f]+\}|\\x[0-9A-Fa-f]{2}|\\.|[^'\\]))'"


def parse_char(tok):
    if tok.startswith('\\u{'):
        return int(tok[3:-1], 16)
    if tok.startswith('\\x'):
        return int(tok[2:], 16)
    if tok.startswith('\\'):
        return {'\\n': 10, '\\r': 13, '\\t': 9, '\\0': 0, "\\'": 39,
                '\\\\': 92, '\\"': 34}[tok]
    return ord(tok)


def parse_range_tables(path):
    text = open(path, encoding='utf-8').read()
    by_name = re.search(r"pub const BY_NAME[^=]*=\s*&\[(.*?)\];", text, re.S)
    if by_name is None:
        names = None
    else:
        names = re.findall(r'\("([^"]+)",\s*([A-Z0-9_]+)\)', by_name.group(1))
    tables = {}
    for m in re.finditer(
            r"pub const ([A-Z0-9_]+): &'static \[\(char, char\)\] =\s*&\[(.*?)\];",
            text, re.S):
        pairs = re.findall(r"\(" + CHAR_RE + r",\s*" + CHAR_RE + r"\)",
                           m.group(2))
        tables[m.group(1)] = [(parse_char(a), parse_char(b)) for a, b in pairs]
    if names is None:
        names = [(c, c) for c in tables]
    return [(n, tables[c]) for n, c in names]


def mbt_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def write_tables(fname, fn_name, doc, entries):
    with open(os.path.join(OUT, fname), 'w') as f:
        f.write('// Generated by scripts/gen_unicode.py. DO NOT EDIT.\n\n')
        f.write('///|\n/// %s\nlet %s : Array[(String, String)] = [\n' %
                (doc, fn_name))
        for name, ranges in entries:
            f.write('  (%s, %s),\n' % (mbt_str(name), mbt_str(enc_ranges(ranges))))
        f.write(']\n')


def main():
    specs = [
        ('general_category.rs', 'general_category_data.mbt', 'gencat_data',
         'General category tables.'),
        ('script.rs', 'script_data.mbt', 'script_data', 'Script tables.'),
        ('script_extension.rs', 'script_extension_data.mbt', 'scx_data',
         'Script extension tables.'),
        ('property_bool.rs', 'property_bool_data.mbt', 'bool_data',
         'Boolean property tables.'),
        ('age.rs', 'age_data.mbt', 'age_data', 'Age tables.'),
        ('grapheme_cluster_break.rs', 'gcb_data.mbt', 'gcb_data',
         'Grapheme cluster break tables.'),
        ('word_break.rs', 'word_break_data.mbt', 'wb_data',
         'Word break tables.'),
        ('sentence_break.rs', 'sentence_break_data.mbt', 'sb_data',
         'Sentence break tables.'),
        ('perl_word.rs', 'perl_word_data.mbt', 'perl_word_data',
         'Perl word (\\\\w) table.'),
    ]
    for src, dst, name, doc in specs:
        write_tables(dst, name, doc, parse_range_tables(os.path.join(SRC, src)))

    # Property names.
    text = open(os.path.join(SRC, 'property_names.rs'), encoding='utf-8').read()
    pairs = re.findall(r'\("([^"]+)",\s*"([^"]+)"\)', text)
    with open(os.path.join(OUT, 'property_names_data.mbt'), 'w') as f:
        f.write('// Generated by scripts/gen_unicode.py. DO NOT EDIT.\n\n')
        f.write('///|\n/// Normalized property name aliases, sorted.\n')
        f.write('let property_names_data : Array[(String, String)] = [\n')
        for a, b in pairs:
            f.write('  (%s, %s),\n' % (mbt_str(a), mbt_str(b)))
        f.write(']\n')

    # Property values.
    text = open(os.path.join(SRC, 'property_values.rs'), encoding='utf-8').read()
    body = text[text.index('= &['):]
    groups = re.findall(r'\(\s*"([^"]+)",\s*&\[(.*?)\],\s*\)', body, re.S)
    with open(os.path.join(OUT, 'property_values_data.mbt'), 'w') as f:
        f.write('// Generated by scripts/gen_unicode.py. DO NOT EDIT.\n\n')
        f.write('///|\n/// Normalized property value aliases per property, sorted.\n')
        f.write('let property_values_data : Array[(String, Array[(String, String)])] = [\n')
        for prop, vals in groups:
            f.write('  (%s, [\n' % mbt_str(prop))
            for a, b in re.findall(r'\("([^"]+)",\s*"([^"]+)"\)', vals):
                f.write('    (%s, %s),\n' % (mbt_str(a), mbt_str(b)))
            f.write('  ]),\n')
        f.write(']\n')

    # Simple case folding: encoded as a string of entries
    # (delta from previous key, count, mapped chars as absolute values).
    text = open(os.path.join(SRC, 'case_folding_simple.rs'), encoding='utf-8').read()
    entries = re.findall(r"\(" + CHAR_RE + r",\s*&\[(.*?)\]\)", text)
    out = []
    prev = 0
    for k, vals in entries:
        kc = parse_char(k)
        vs = [parse_char(v) for v in re.findall(CHAR_RE, vals)]
        out.append(enc_num(kc - prev))
        out.append(enc_num(len(vs)))
        for v in vs:
            out.append(enc_num(v))
        prev = kc
    with open(os.path.join(OUT, 'case_folding_data.mbt'), 'w') as f:
        f.write('// Generated by scripts/gen_unicode.py. DO NOT EDIT.\n\n')
        f.write('///|\n/// Simple case folding table (all pairs).\n')
        f.write('let case_folding_data : String = %s\n' % mbt_str(''.join(out)))


main()
