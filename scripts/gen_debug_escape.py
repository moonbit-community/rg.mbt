#!/usr/bin/env python3
"""Generates core/debug_escape_data.mbt: the code points that Rust's `{:?}`
escapes as `\\u{...}` inside a string (non-printable and grapheme-extending
characters). The input is the output of scripts/debug_escape.rs, built with
the Rust toolchain that builds ripgrep:

  cargo new dbgesc && cp scripts/debug_escape.rs dbgesc/src/main.rs
  (cd dbgesc && cargo +1.97.1 run -q --release) > ranges.txt
  python3 scripts/gen_debug_escape.py ranges.txt > core/debug_escape_data.mbt
  moon fmt
"""
import sys
pairs = [tuple(int(x, 16) for x in line.split()) for line in open(sys.argv[1]) if line.strip()]
print('// Generated by scripts/gen_debug_escape.py. DO NOT EDIT.')
print('')
print('///|')
print('/// Inclusive ranges of code points escaped by Rust\'s `{:?}` (as')
print('/// `\\\\u{...}`), as consecutive start/end pairs in ascending order.')
print('let debug_escape_ranges : FixedArray[Int] = [')
for a, b in pairs:
    print(f'  0x{a:X}, 0x{b:X},')
print(']')
